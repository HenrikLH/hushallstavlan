 assert.equal(await pg.locator('[data-act="familjOpen"]').count(),1,'Utvecklarvyn ska bli synlig');
 await click('[data-act="familjOpen"]');
 assert.ok((await main()).includes('6 personer'),'Familj använder riktiga födelsedagar');
