// Utvecklarläge: Familj / släktträd. Testdata ska aldrig sparas.
const assert=require('node:assert/strict');
module.exports=async(pg,h)=>{
 const sh=()=>h.sheet('Inställningar'),before=()=>{const r=sh().find(x=>x[0]==='onskelista');return r?r[1]:''};
 const fr=sh().find(x=>x[0]==='fodelsedagar');if(fr)fr[1]=JSON.stringify([{namn:'Testperson',datum:'10-25',ar:1990}]);else sh().push(['fodelsedagar',JSON.stringify([{namn:'Testperson',datum:'10-25',ar:1990}])]);
 await pg.reload();await h.idle(1000);
 const initial=before();
 const click=async(sel)=>{await pg.locator(sel).first().click();await h.idle(450)};
 assert.equal(await pg.locator('[data-act="familjOpen"]').count(),0,'Förhandsvisningen får inte finnas i normalvy');
 await click('[data-act="settings"]');
 if(!(await pg.locator('details[data-k="pref-avancerat"]').evaluate(el=>el.open)))await click('details[data-k="pref-avancerat"] > summary');
 assert.equal(await pg.locator('[data-act="familjOpen"]').count(),0,'Testknappen dold utan utvecklarläge');
 await click('[data-act="dev"]');
 await h.idle(350);
 assert.equal(await pg.locator('[data-act="familjOpen"]').count(),1,'Testknappen syns i utvecklarläge');
 await click('[data-act="familjOpen"]');
 assert.equal(await pg.evaluate(()=>document.body.dataset.view),'familj');
 assert.ok((await pg.locator('main').innerText()).includes('Förhandsvisning'));
 await h.shot('familj-dev-start');
 await click('[data-act="nav"][data-id="slakt"]');
 assert.equal(await pg.locator('svg.fam-svg').count(),1,'Fokusträdet syns');
 await h.shot('familj-dev-fokus');
 await click('[data-act="slaktVy"][data-id="alla"]');
 assert.equal(await pg.locator('svg.fam-full-svg').count(),1,'Hela släktträdet syns');
 assert.equal(await pg.locator('svg.fam-full-svg .fam-node').count(),10,'Alla tio testpersoner visas');
 await h.shot('familj-dev-hela');
 await click('[data-act="slaktVy"][data-id="fokus"]');
 await click('svg.fam-svg .fam-node[data-id="Anna|05-12"]');
 assert.ok((await pg.locator('.fam-focus').innerText()).includes('Anna'),'Fokus kan flyttas');
 assert.equal(before(),initial,'Testvyn får inte skriva i familjedata');
 await click('[data-act="nav"][data-id="familj"]');
 await click('[data-act="nav"][data-id="fod"]');
 assert.equal(await pg.locator('[data-act="fodMode"]').count(),3,'Födelsedagarnas tre visningar är kvar');
 await click('[data-act="nav"][data-id="familj"]');
 await click('[data-act="nav"][data-id="oversikt"]');
 await click('[data-act="settings"]');
 if(!(await pg.locator('details[data-k="pref-avancerat"]').evaluate(el=>el.open)))await click('details[data-k="pref-avancerat"] > summary');
 await click('[data-act="dev"]');
 await h.idle(300);
 assert.equal(await pg.locator('[data-act="familjOpen"]').count(),0,'Testknappen försvinner när utvecklarläge stängs');
 assert.equal(before(),initial,'Inga data har ändrats');
};
