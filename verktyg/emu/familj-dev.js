// Familj i utvecklarläge: riktiga födelsedagspersoner, relationer och dataisolering.
const assert=require('node:assert/strict');
module.exports=async(pg,h)=>{
 const sheet=()=>h.sheet('Inställningar'),row=k=>sheet().find(r=>r[0]===k);
 const setRow=(k,v)=>{const r=row(k);if(r)r[1]=v;else sheet().push([k,v])};
 const birthdays=[['Anna','05-12'],['Erik','06-05'],['Maja','08-18'],['Leo','11-03'],['Ella','08-29'],['Morfar','03-02']].map(([namn,datum])=>({namn,datum}));
 setRow('fodelsedagar',JSON.stringify(birthdays));
 const origWishes=JSON.parse(row('onskelista')?.[1]||'[]'),other=origWishes.filter(x=>!x.fod);
 setRow('onskelista',JSON.stringify(other));
 await pg.reload();await h.idle(1400);
 const click=async s=>{await pg.locator(s).first().click();await h.idle(380)},main=()=>pg.locator('main').innerText();
 assert.equal(await pg.locator('[data-act="familjOpen"]').count(),0,'Familj syns inte utanför DEV');
 await click('[data-act="settings"]');
 if(!(await pg.locator('details[data-k="pref-avancerat"]').evaluate(x=>x.open)))await click('details[data-k="pref-avancerat"] > summary');
 await click('[data-act="dev"]');
 assert.equal(await pg.locator('[data-act="familjOpen"]').count(),1,'Utvecklarvyn ska bli synlig');
 await click('[data-act="familjOpen"]');
 assert.ok((await main()).includes('6 personer'),'Familj använder riktiga födelsedagar');
 assert.ok(!(await main()).includes('Britt'),'Gamla demopersoner får inte visas');
 await h.shot('familj-dev-riktig-start');
 await click('[data-act="nav"][data-id="slaktPersoner"]');
 assert.equal(await pg.locator('[data-act="slaktEdit"]').count(),6,'Alla födelsedagspersoner finns att redigera');
 await h.shot('familj-dev-personer');
 await click('[data-act="slaktEdit"][data-id="Anna|05-12"]');
 assert.equal(await pg.locator('form[data-form="slaktRel"]').count(),1);
 await pg.selectOption('select[name="slPartner"]','Erik|06-05');
 await pg.locator('input[name="slChild"][value="Maja|08-18"]').check();
 await pg.locator('input[name="slChild"][value="Leo|11-03"]').check();
 await h.shot('familj-dev-relationer');
 await click('form[data-form="slaktRel"] .tb.strong');await h.waitFlush();
 const fst=JSON.parse(row('onskelista')[1]),sr=fst.find(x=>x.fod)?.sr;
 assert.ok(sr,'Relationerna lagras under födelsedagsobjektet');
 assert.ok(sr.par['Maja|08-18'].includes('Anna|05-12'),'Anna har Maja som barn');
 assert.equal(sr.partners.length,1,'Partner sparad');
 assert.deepEqual(fst.filter(x=>!x.fod),other,'Övriga önskemål ska bevaras');
 await click('[data-act="slaktEdit"][data-id="Maja|08-18"]');
 await pg.locator('input[name="slParent"][value="Erik|06-05"]').check();
 await pg.locator('input[name="slSibling"][value="Morfar|03-02"]').check();
 await pg.locator('input[name="slChild"][value="Ella|08-29"]').check();
 await click('form[data-form="slaktRel"] .tb.strong');await h.waitFlush();
 const newWishes=JSON.parse(row('onskelista')[1]).find(x=>x.fod).sr;
 assert.ok(newWishes.siblings.some(p=>p.includes('Morfar|03-02')&&p.includes('Maja|08-18')),'Syskon sparas utan att tilldela föräldrar');
 assert.deepEqual(newWishes.par['Maja|08-18'].sort(),['Anna|05-12','Erik|06-05'].sort(),'Båda föräldrarna valdes i ett steg');
 await click('[data-act="nav"][data-id="familj"]');
 await click('[data-act="nav"][data-id="slakt"]');
 await click('[data-act="slaktVy"][data-id="alla"]');
 assert.equal(await pg.locator('svg.fam-full-svg .fam-node').count(),6,'Syskon utan föräldrar ska synas i trädet');
 assert.equal(await pg.locator('main .sh').filter({hasText:'Ännu inte placerade'}).count(),1,'Ej placerade personer ska visas separat');
 await h.shot('familj-dev-hela');
 await click('[data-act="slaktLayout"][data-id="hybrid"]');
 assert.equal(await pg.locator('svg.fam-hybrid-svg .fam-h-node').count(),6,'Hybrid visar alla kopplade personer');
 await h.shot('familj-dev-hybrid');
 await click('[data-act="slaktHybridLock"]');
 assert.ok(await pg.locator('svg.fam-hybrid-svg .fam-pin').count()>0,'En nod går att låsa');
 await click('[data-act="slaktHybridZoom"][data-id="plus"]');
 assert.ok((await pg.locator('.fam-hybrid .fam-zoom').innerText()).includes('125'),'Hybridzoom fungerar');
 await pg.reload();await h.idle(1100);
 await click('[data-act="familjOpen"]');await click('[data-act="nav"][data-id="slakt"]');
 assert.equal(await pg.locator('svg.fam-hybrid-svg').count(),1,'Vald layout sparas per enhet');
 await click('[data-act="slaktLayout"][data-id="trad"]');
 const width=Number(await pg.locator('svg.fam-full-svg').getAttribute('width'));
 await click('[data-act="slaktZoom"][data-id="plus"]');
 assert.ok(Number(await pg.locator('svg.fam-full-svg').getAttribute('width'))>width,'Zoom fungerar');
 await click('[data-act="slaktZoom"][data-id="minus"]');
 await click('svg.fam-full-svg .fam-node[data-id="Maja|08-18"]');
 assert.equal(await pg.locator('svg.fam-svg').count(),1,'Vald person öppnas i fokus');
 assert.ok((await pg.locator('.fam-focus').innerText()).includes('Maja'));
 await h.shot('familj-dev-fokus');
 // Cykler får inte gå att spara.
 await click('[data-act="slaktEdit"][data-id="Maja|08-18"]');
 await pg.locator('input[name="slParent"][value="Ella|08-29"]').check();
 await click('form[data-form="slaktRel"] .tb.strong');
 assert.equal(await pg.locator('form[data-form="slaktRel"]').count(),1,'Cirkulär relation avvisas');
 await click('[data-act="sheetClose"]');
 const unchanged=JSON.stringify(birthdays);
 assert.equal(row('fodelsedagar')[1],unchanged,'Födelsedagar är helt oförändrade');
 await pg.reload();await h.idle(1200);
 await click('#nav [data-act="nav"][data-id="oversikt"]');
 await click('[data-act="nav"][data-id="fod"]');
 assert.equal(await pg.locator('[data-act="fodMode"]').count(),3,'Födelsedagarnas tre visningar finns kvar');
 await click('#nav [data-act="nav"][data-id="oversikt"]');
 await click('[data-act="settings"]');
 if(!(await pg.locator('details[data-k="pref-avancerat"]').evaluate(x=>x.open)))await click('details[data-k="pref-avancerat"] > summary');
 await click('[data-act="dev"]');
 assert.equal(await pg.locator('[data-act="familjOpen"]').count(),0,'Förhandsvisningen döljs när utvecklarläge är av');
};
