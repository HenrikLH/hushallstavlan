// Mobilens släktträd med många barn: förhandsvisningen får inte bli bred eller klottrig.
const assert=require('node:assert/strict');
module.exports=async(pg,h)=>{
 const rows=h.sheet('Inställningar'),set=(k,v)=>{const r=rows.find(x=>x[0]===k);if(r)r[1]=v;else rows.push([k,v])};
 const roots=[['Farmor','01-01'],['Farfar','01-02'],['FörälderA','01-03'],['FörälderB','01-04']];
 const children=Array.from({length:24},(_,i)=>['Barn'+String(i+1).padStart(2,'0'),'02-'+String(i+1).padStart(2,'0')]);
 const ids=roots.concat(children),key=x=>x[0]+'|'+x[1],par={};
 par[key(roots[2])]=[key(roots[0]),key(roots[1])];
 children.forEach(c=>par[key(c)]=[key(roots[2]),key(roots[3])]);
 set('fodelsedagar',JSON.stringify(ids.map(([namn,datum])=>({namn,datum}))));
 const wishes=JSON.parse(rows.find(x=>x[0]==='onskelista')?.[1]||'[]').filter(x=>!x.fod);
 wishes.push({fod:1,add:[],del:[],col:{},fam:[],fm:{},pr:{},pb:{},sr:{par,partners:[[key(roots[2]),key(roots[3])]],siblings:[]}});
 set('onskelista',JSON.stringify(wishes));
 await pg.reload();await h.idle(1300);
 const click=async s=>{await pg.locator(s).first().click();await h.idle(300)};
 await click('[data-act="settings"]');
 if(!(await pg.locator('details[data-k="pref-avancerat"]').evaluate(x=>x.open)))await click('details[data-k="pref-avancerat"] > summary');
 await click('[data-act="dev"]');
 await click('[data-act="familjOpen"]');
 await click('[data-act="nav"][data-id="slakt"]');
 await click('[data-act="slaktLayout"][data-id="trad"]');
 await click('[data-act="slaktVy"][data-id="alla"]');
 assert.equal(await pg.locator('.fam-gen-col').count(),3,'Tre genererationskolumner');
 assert.equal(await pg.locator('.fam-gen-col .fam-mini').count(),9,'Barnkullen är komprimerad till fem noder');
 assert.equal(await pg.locator('.fam-gen-col .fam-gen-more').count(),1,'Barnkullen kan expanderas');
 const w=await pg.locator('.fam-gen-col').last().evaluate(x=>x.getBoundingClientRect().width);
 assert.ok(w<310,'Kolumnen får inte bli för bred för telefon');
 await h.shot('familj-stor-trad');
 await click('.fam-gen-more');
 assert.equal(await pg.locator('.fam-gen-col .fam-mini').count(),28,'Alla barn är tillgängliga vid expandering');
 await click('[data-act="slaktLayout"][data-id="hybrid"]');
 assert.equal(await pg.locator('.fam-h-overview svg').count(),0,'Översikt utan linjenät');
 await click('[data-act="slaktFocus"][data-id="FörälderA|01-03"]');
 assert.ok(await pg.locator('.fam-hybrid-svg .fam-h-node').count()<=7,'Fokus visar högst sju noder trots 28 personer');
 assert.equal(await pg.locator('.fam-hybrid .fam-h-edge').count()<=9,true,'Ingen spagetti av relationslinjer');
 assert.ok((await pg.locator('.fam-hybrid').innerText()).includes('21 fler'),'Övriga barn är åtkomliga');
 await h.shot('familj-stor-hybrid');
 await click('[data-act="slaktChildrenMore"]');
 assert.ok((await pg.locator('.fam-hybrid').innerText()).includes('Barn24'),'Alla barn kan visas i listan');
};
